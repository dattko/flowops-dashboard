create view public.dashboard_weekly_sales
with (security_invoker = true)
as
select
  stat_date,
  sum(order_count)::integer as order_count,
  sum(gross_revenue)::bigint as gross_revenue
from public.daily_channel_metrics
group by stat_date;

create view public.dashboard_channel_share
with (security_invoker = true)
as
with latest as (
  select max(stat_date) as max_date
  from public.daily_channel_metrics
)
select
  channels.code,
  channels.name,
  sum(metrics.order_count)::integer as order_count,
  round(
    100.0 * sum(metrics.order_count)
      / nullif(sum(sum(metrics.order_count)) over (), 0),
    1
  ) as share_percent
from public.daily_channel_metrics as metrics
join public.sales_channels as channels on channels.id = metrics.channel_id
cross join latest
where metrics.stat_date > latest.max_date - 7
group by channels.code, channels.name;

grant select on public.dashboard_weekly_sales, public.dashboard_channel_share
to authenticated, service_role;

