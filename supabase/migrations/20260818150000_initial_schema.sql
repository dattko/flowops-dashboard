create policy "profiles_select_self_or_admin"
on public.profiles for select to authenticated
using ((select auth.uid()) = id or (select public.is_admin()));

create policy "profiles_update_self"
on public.profiles for update to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

create policy "channels_public_read"
on public.sales_channels for select to anon, authenticated
using (true);

create policy "channels_admin_write"
on public.sales_channels for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy "products_public_read_active"
on public.products for select to anon, authenticated
using (status = 'active');

create policy "products_admin_read_all"
on public.products for select to authenticated
using ((select public.is_admin()));

create policy "products_admin_write"
on public.products for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy "inventory_admin_all"
on public.inventory for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

