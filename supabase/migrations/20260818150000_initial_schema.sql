on public.orders for select to authenticated
using (user_id = (select auth.uid()) or (select public.is_admin()));

create policy "orders_admin_write"
on public.orders for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy "order_items_select_own_or_admin"
on public.order_items for select to authenticated
using (
  exists (
    select 1
    from public.orders
    where orders.id = order_items.order_id
      and (orders.user_id = (select auth.uid()) or (select public.is_admin()))
  )
);

create policy "order_items_admin_write"
on public.order_items for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy "daily_metrics_admin_all"
on public.daily_channel_metrics for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

