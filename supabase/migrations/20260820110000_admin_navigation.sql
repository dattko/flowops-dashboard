create table public.admin_navigation_menus (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  href text not null,
  icon text not null
    check (icon in ('dashboard', 'orders', 'inventory', 'customers', 'reports', 'settings')),
  section text not null default 'main'
    check (section in ('main', 'footer')),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger admin_navigation_menus_set_updated_at
before update on public.admin_navigation_menus
for each row execute function public.set_updated_at();

alter table public.admin_navigation_menus enable row level security;

create policy "admin_navigation_menus_authenticated_read"
on public.admin_navigation_menus for select to authenticated
using (true);

create policy "admin_navigation_menus_admin_write"
on public.admin_navigation_menus for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

grant select on public.admin_navigation_menus to authenticated;
grant insert, update, delete on public.admin_navigation_menus to authenticated;
grant usage, select on sequence public.admin_navigation_menus_id_seq
to authenticated, service_role;

