create or replace function public.get_admin_navigation()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'code', menus.code,
        'label', menus.label,
        'href', menus.href,
        'icon', menus.icon,
        'section', menus.section
      )
      order by menus.section, menus.sort_order, menus.id
    ),
    '[]'::jsonb
  )
  from public.admin_navigation_menus as menus
  where menus.is_active = true;
$$;

revoke all on function public.get_admin_navigation() from public;
grant execute on function public.get_admin_navigation() to authenticated;

comment on table public.admin_navigation_menus is
  'Configurable sidebar navigation for the admin application.';
