-- Order detail data for the admin order detail page.

alter table public.orders
add column customer_phone text;

alter table public.order_items
add column product_sku text;

update public.orders
set customer_phone = '010-0000-' || right(order_number, 4)
where customer_phone is null;

update public.order_items
set product_sku = products.sku
from public.products
where products.id = order_items.product_id
  and order_items.product_sku is null;

create table public.order_payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null unique references public.orders (id) on delete cascade,
  method text not null
    check (method in ('card', 'bank_transfer', 'virtual_account', 'kakao_pay')),
  status text not null
    check (status in ('pending', 'paid', 'partially_refunded', 'refunded', 'failed', 'cancelled')),
  product_amount integer not null check (product_amount >= 0),
  discount_amount integer not null default 0 check (discount_amount >= 0),
  shipping_fee integer not null default 0 check (shipping_fee >= 0),
  paid_amount integer not null check (paid_amount >= 0),
  transaction_id text unique,
  paid_at timestamptz,
  refunded_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_shipments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null unique references public.orders (id) on delete cascade,
  recipient_name text not null,
  recipient_phone text not null,
  postal_code text not null,
  address_line1 text not null,
  address_line2 text,
  delivery_memo text,
  carrier text,
  tracking_number text unique,
  shipped_at timestamptz,
  delivered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders (id) on delete cascade,
  status text not null
    check (status in ('paid', 'preparing', 'shipping', 'delivered', 'cancelled')),
  note text,
  changed_at timestamptz not null default now()
);

create index order_status_history_order_changed_idx
on public.order_status_history (order_id, changed_at desc);

create trigger order_payments_set_updated_at
before update on public.order_payments
for each row execute function public.set_updated_at();

create trigger order_shipments_set_updated_at
before update on public.order_shipments
for each row execute function public.set_updated_at();

alter table public.order_payments enable row level security;
alter table public.order_shipments enable row level security;
alter table public.order_status_history enable row level security;

create policy "order_payments_select_own_or_admin"
on public.order_payments for select to authenticated
using (
  exists (
    select 1
    from public.orders
    where orders.id = order_payments.order_id
      and (orders.user_id = (select auth.uid()) or (select public.is_admin()))
  )
);

create policy "order_payments_admin_write"
on public.order_payments for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

